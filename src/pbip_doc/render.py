"""Markdown and JSON output."""

from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from dataclasses import asdict
from typing import Any

from pbip_doc import __version__
from pbip_doc.lineage import Lineage, ObjRef
from pbip_doc.model import Measure, SemanticModel, Table
from pbip_doc.report import Report
from pbip_doc.rules import Finding, Severity


def _cell(text: str | None) -> str:
    if not text:
        return ""
    return text.replace("|", "\\|").replace("\r", "").replace("\n", "<br>")


def _code(text: str) -> str:
    return f"`{text}`" if "`" not in text else f"`` {text} ``"


class _Slugger:
    """Reproduces GitHub's heading anchors, including the -1, -2 suffixes for duplicates."""

    def __init__(self) -> None:
        self.seen: Counter[str] = Counter()

    def __call__(self, heading: str) -> str:
        base = re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")
        count = self.seen[base]
        self.seen[base] += 1
        return base if count == 0 else f"{base}-{count}"


def _objects(refs: set[ObjRef] | None) -> str:
    return ", ".join(_code(str(r)) for r in sorted(refs or ()))


def _column_notes(model: SemanticModel, table: Table) -> dict[str, list[str]]:
    notes: dict[str, list[str]] = defaultdict(list)
    for c in table.columns:
        if c.is_key:
            notes[c.name].append("key")
        if c.is_hidden:
            notes[c.name].append("hidden")
        if c.is_calculated:
            notes[c.name].append("calculated")
        if c.sort_by:
            notes[c.name].append(f"sorted by {_code(c.sort_by)}")
        if c.data_category:
            notes[c.name].append(c.data_category)
    for r in model.relationships:
        if r.from_table == table.name:
            notes[r.from_column].append(f"→ {_code(r.to_table)}")
        if r.to_table == table.name:
            notes[r.to_column].append(f"← {_code(r.from_table)}")
    return notes


def _mermaid(model: SemanticModel) -> list[str]:
    tables = [t for t in model.tables if not t.is_calculation_group]
    ids = {t.name: f"t{i}" for i, t in enumerate(tables)}
    lines = ["```mermaid", "flowchart LR"]
    for t in tables:
        label = t.name.replace('"', "'")
        shape = f'{ids[t.name]}[("{label}")]' if t.is_measure_table else f'{ids[t.name]}["{label}"]'
        lines.append(f"    {shape}")
    for r in model.relationships:
        if r.from_table not in ids or r.to_table not in ids:
            continue
        label = f"{r.cardinality} · {r.from_column}".replace('"', "'")
        if r.cross_filter.lower() == "bothdirections":
            arrow = f'<-- "{label}" -->'
        elif not r.is_active:
            arrow = f'-. "{label} (inactive)" .->'
        else:
            arrow = f'-- "{label}" -->'
        lines.append(f"    {ids[r.from_table]} {arrow} {ids[r.to_table]}")
    lines.append("```")
    return lines


def _measure_block(m: Measure, lineage: Lineage, out: list[str]) -> None:
    ref = ObjRef("measure", m.table, m.name)
    out.append(f"#### {m.name}")
    out.append("")
    if m.description:
        out += [m.description, ""]
    facts = []
    if m.format_string:
        facts.append(f"Format {_code(m.format_string)}")
    if m.is_hidden:
        facts.append("hidden")
    if lineage.has_report and not lineage.is_used(ref):
        facts.append("**not used**")
    if facts:
        out += [" · ".join(facts), ""]
    out += ["```dax", m.expression.strip(), "```", ""]
    if deps := lineage.depends_on.get(ref):
        out.append(f"- **Depends on:** {_objects(deps)}")
    if users := lineage.used_by.get(ref):
        out.append(f"- **Used by:** {_objects(users)}")
    if visuals := lineage.visuals.get(ref):
        out.append(f"- **In the report:** {', '.join(sorted(visuals))}")
    if deps or users or visuals:
        out.append("")


def to_markdown(
    model: SemanticModel,
    lineage: Lineage,
    findings: list[Finding],
    report: Report | None = None,
) -> str:
    slug = _Slugger()
    out: list[str] = []
    data_tables = [t for t in model.tables if not t.is_calculation_group]
    calc_groups = [t for t in model.tables if t.is_calculation_group]
    severities = Counter(f.severity for f in findings)

    out += [f"# {model.name} — semantic model", ""]
    slug(f"{model.name} — semantic model")
    out += [
        f"> Generated by [pbip-doc](https://github.com/adonaismarrero/pbip-documenter) "
        f"{__version__} from the PBIP/TMDL files. Do not edit by hand.",
        "",
    ]

    summary = [
        ("Tables", str(len(data_tables))),
        (
            "Columns",
            f"{len(model.columns)} ({sum(c.is_calculated for c in model.columns)} calculated)",
        ),
        ("Measures", str(len(model.measures))),
        ("Calculation groups", str(len(calc_groups))),
        ("Relationships", str(len(model.relationships))),
        ("Security roles", str(len(model.roles))),
    ]
    if report:
        summary.append(("Report", f"{len(report.pages)} page(s), {len(report.visuals)} visual(s)"))
    summary.append(
        (
            "Checks",
            f"{severities[Severity.ERROR]} errors · {severities[Severity.WARNING]} warnings · "
            f"{severities[Severity.INFO]} info",
        )
    )
    if model.compatibility_level:
        summary.append(("Compatibility level", model.compatibility_level))
    out += ["| | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in summary] + [""]

    sections = ["Diagram", "Tables", "Measures"]
    if calc_groups:
        sections.append("Calculation groups")
    sections.append("Relationships")
    if model.roles:
        sections.append("Row-level security")
    if model.expressions:
        sections.append("Parameters and shared queries")
    if report:
        sections.append("Report")
    sections.append("Quality checks")
    anchors = {s: slug(s) for s in sections}
    out += ["**Contents:** " + " · ".join(f"[{s}](#{anchors[s]})" for s in sections), ""]

    out += ["## Diagram", "", *_mermaid(model), ""]

    out += ["## Tables", ""]
    for t in data_tables:
        out += [f"### {t.name}", ""]
        slug(t.name)
        badges = []
        if t.is_hidden:
            badges.append("hidden")
        if t.data_category == "Time":
            badges.append("date table")
        if t.is_measure_table:
            badges.append("measure table")
        if badges:
            out += [" · ".join(f"*{b}*" for b in badges), ""]
        if t.description:
            out += [t.description, ""]
        visible = [c for c in t.columns if not (t.is_measure_table and c.is_hidden)]
        if visible:
            notes = _column_notes(model, t)
            out += ["| Column | Type | Description | Notes |", "|---|---|---|---|"]
            for c in visible:
                out.append(
                    f"| {_cell(c.name)} | {c.data_type or ''} | {_cell(c.description)} | "
                    f"{_cell(', '.join(notes.get(c.name, [])))} |"
                )
            out.append("")
            for c in visible:
                if c.expression:
                    out += [f"**{c.name}** (calculated)", "", "```dax", c.expression, "```", ""]
        for h in t.hierarchies:
            levels = " › ".join(name for name, _ in h.levels)
            out += [f"Hierarchy **{h.name}**: {levels}", ""]
        if t.measures:
            out += [f"Measures: {len(t.measures)} (see [Measures](#{anchors['Measures']}))", ""]
        for p in t.partitions:
            if p.source:
                lang = "powerquery" if p.kind == "m" else "dax"
                mode = f", {p.mode}" if p.mode else ""
                out += [
                    f"<details><summary>Source ({p.kind}{mode})</summary>",
                    "",
                    f"```{lang}",
                    p.source,
                    "```",
                    "",
                    "</details>",
                    "",
                ]

    out += ["## Measures", ""]
    for t in model.tables:
        if not t.measures:
            continue
        folders: dict[str, list[Measure]] = defaultdict(list)
        for m in t.measures:
            folders[m.display_folder or ""].append(m)
        for folder in sorted(folders):
            heading = f"{t.name} › {folder}" if folder else t.name
            out += [f"### {heading}", ""]
            slug(heading)
            for m in folders[folder]:
                slug(m.name)
                _measure_block(m, lineage, out)

    if calc_groups:
        out += ["## Calculation groups", ""]
        for t in calc_groups:
            slug(t.name)
            out += [f"### {t.name}", ""]
            if t.description:
                out += [t.description, ""]
            if t.calculation_group_precedence is not None:
                out += [f"Precedence: {t.calculation_group_precedence}", ""]
            for item in t.calculation_items:
                out += [f"**{item.name}**", "", "```dax", item.expression, "```", ""]
                if item.format_string_expression:
                    out += [f"Format string: {_code(item.format_string_expression)}", ""]

    out += ["## Relationships", ""]
    if model.relationships:
        out += ["| From (many side) | To (one side) | Cardinality | Filter | Active |"]
        out += ["|---|---|---|---|---|"]
        for r in model.relationships:
            direction = "both" if r.cross_filter.lower() == "bothdirections" else "single"
            out.append(
                f"| {_cell(r.from_table)}[{_cell(r.from_column)}] | "
                f"{_cell(r.to_table)}[{_cell(r.to_column)}] | {r.cardinality} | {direction} | "
                f"{'yes' if r.is_active else 'no'} |"
            )
        out.append("")
    else:
        out += ["No relationships.", ""]

    if model.roles:
        out += ["## Row-level security", ""]
        for role in model.roles:
            slug(role.name)
            out += [f"### {role.name}", ""]
            if role.description:
                out += [role.description, ""]
            out += [f"Permission: {role.permission or 'read'}", ""]
            for table, expression in role.table_filters.items():
                out += [f"Filter on **{table}**:", "", "```dax", expression, "```", ""]

    if model.expressions:
        out += ["## Parameters and shared queries", ""]
        out += ["| Name | Kind | Description |", "|---|---|---|"]
        for e in model.expressions:
            out.append(f"| {_cell(e.name)} | {e.kind} | {_cell(e.description)} |")
        out.append("")

    if report:
        out += ["## Report", ""]
        for page in report.pages:
            slug(page.display_name)
            out += [f"### {page.display_name}", ""]
            out += ["| Visual | Type | Fields |", "|---|---|---|"]
            for v in page.visuals:
                fields = ", ".join(
                    _code(
                        f"[{f.name}]" if f.kind == "Measure" else f"{f.table}[{f.level or f.name}]"
                    )
                    for f in v.fields
                )
                out.append(f"| {_cell(v.title or v.name)} | {v.visual_type} | {_cell(fields)} |")
            out.append("")

    out += ["## Quality checks", ""]
    if findings:
        out += ["| Severity | Rule | Object | Finding |", "|---|---|---|---|"]
        for f in findings:
            out.append(f"| {f.severity} | {f.code} | {_cell(_code(f.obj))} | {_cell(f.message)} |")
        out.append("")
    else:
        out += ["No findings. ✅", ""]
    return "\n".join(out).rstrip() + "\n"


def to_json(
    model: SemanticModel, lineage: Lineage, findings: list[Finding], report: Report | None
) -> str:
    def refs(values: set[ObjRef] | None) -> list[str]:
        return [str(v) for v in sorted(values or ())]

    payload: dict[str, Any] = {
        "generator": f"pbip-doc {__version__}",
        "model": asdict(model),
        "lineage": {
            str(obj): {
                "depends_on": refs(lineage.depends_on.get(obj)),
                "used_by": refs(lineage.used_by.get(obj)),
                "visuals": sorted(lineage.visuals.get(obj, ())),
                "used": lineage.is_used(obj) if lineage.has_report else None,
            }
            for obj in sorted(set(lineage.depends_on) | set(lineage.used_by) | set(lineage.visuals))
        },
        "report": asdict(report) if report else None,
        "findings": [
            {"severity": str(f.severity), "code": f.code, "object": f.obj, "message": f.message}
            for f in findings
        ],
    }
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
